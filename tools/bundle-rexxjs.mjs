#!/usr/bin/env node
// tools/bundle-rexxjs.mjs -- vendor RexxJS's interpreter and bundle it as one
// ES module a sae page can import.
//
//   node tools/bundle-rexxjs.mjs [path/to/RexxJS]      (default ../RexxJS)
//
// 1. Copies the closure of core/src/interpreter.js and core/src/parser.js
//    (every relative require, followed) into vendor/rexxjs/core/src/, as
//    they are: changes for sae are made there, and go back upstream later.
//    vendor/rexxjs/UPSTREAM records the commit they came from. With
//    --from-vendor it skips the copy and bundles what is already vendored.
// 2. Writes site/rexxsheet/rexxjs.js: each module as a function of
//    (module, exports, require, console, global) in one table, a require that
//    resolves "./x" against the requiring module, Node's built-ins as empty
//    objects (as webpack's `fallback: false` gives them; a page has no fs,
//    no process, no network but its own), a console that prints, and a
//    `global` of the bundle's own (reads fall through to globalThis, writes
//    stay in the bundle, so RexxJS's globals are not the page's). It
//    exports RexxInterpreter and parse.
//
// Node is needed only to regenerate; the bundle is committed.
import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const VENDOR = path.join(ROOT, "vendor/rexxjs");
const OUT = path.join(ROOT, "site/rexxsheet/rexxjs.js");
const ENTRIES = ["interpreter.js", "parser.js"];

const fromVendor = process.argv.includes("--from-vendor");
const upstream = path.resolve(process.argv.slice(2).find((a) => !a.startsWith("--")) ?? path.join(ROOT, "../RexxJS"));
const srcDir = fromVendor ? path.join(VENDOR, "core/src") : path.join(upstream, "core/src");

// Every module reachable from the entries by a relative require.
function closure(dir) {
  const seen = new Map();
  const walk = (rel) => {
    if (seen.has(rel)) return;
    const text = fs.readFileSync(path.join(dir, rel), "utf8");
    seen.set(rel, text);
    for (const m of text.matchAll(/require\(\s*["']([^"']+)["']\s*\)/g)) {
      if (!m[1].startsWith(".")) continue;
      const to = resolve(rel, m[1]);
      if (fs.existsSync(path.join(dir, to))) walk(to);
    }
  };
  ENTRIES.forEach(walk);
  return seen;
}

function resolve(from, spec) {
  let p = path.posix.normalize(path.posix.join(path.posix.dirname(from), spec));
  if (!p.endsWith(".js")) p += ".js";
  return p;
}

const mods = closure(srcDir);

if (!fromVendor) {
  fs.rmSync(path.join(VENDOR, "core/src"), { recursive: true, force: true });
  for (const [rel, text] of mods) {
    const to = path.join(VENDOR, "core/src", rel);
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.writeFileSync(to, text);
  }
  fs.copyFileSync(path.join(upstream, "LICENSE"), path.join(VENDOR, "LICENSE"));
  const commit = execSync("git rev-parse HEAD", { cwd: upstream }).toString().trim();
  fs.writeFileSync(path.join(VENDOR, "UPSTREAM"),
    `https://github.com/RexxJS/RexxJS ${commit}\n` +
    `The closure of core/src/${ENTRIES.join(" and core/src/")}, by tools/bundle-rexxjs.mjs.\n`);
}

const names = [...mods.keys()].sort();
let out = `// GENERATED by tools/bundle-rexxjs.mjs from vendor/rexxjs (${names.length} modules): do not edit.
// RexxJS (MIT, vendor/rexxjs/LICENSE) as one ES module for a sae page.
const __console = {
  log: (...a) => print(a.join(" ")), info: (...a) => print(a.join(" ")),
  warn: (...a) => print("warn: " + a.join(" ")), error: (...a) => print("error: " + a.join(" ")),
  debug: () => {}, trace: () => {},
};
const __global = Object.create(globalThis);
const __modules = {
`;
for (const rel of names) {
  out += `${JSON.stringify(rel)}: function (module, exports, require, console, global) {\n${mods.get(rel)}\n},\n`;
}
out += `};
const __cache = {};
function __load(rel) {
  if (__cache[rel]) return __cache[rel].exports;
  const module = { exports: {} };
  __cache[rel] = module;
  const require = (spec) => {
    if (!spec.startsWith(".")) return {};
    let p = spec.replace(/^\\.\\//, "");
    if (!p.endsWith(".js")) p += ".js";
    if (!(p in __modules)) throw new Error("rexxjs: no module " + spec + " (from " + rel + ")");
    return __load(p);
  };
  __modules[rel].call(module.exports, module, module.exports, require, __console, __global);
  return module.exports;
}
export const { RexxInterpreter } = __load("interpreter.js");
export const { parse } = __load("parser.js");
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
print_(`${names.length} modules, ${out.split("\n").length} lines -> ${path.relative(ROOT, OUT)}`);

function print_(s) { process.stdout.write(s + "\n"); }
